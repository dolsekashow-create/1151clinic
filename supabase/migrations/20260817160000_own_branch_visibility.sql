--  Purpose   : يرى المستخدم الفروع المُسندة إليه دائمًا.
--
--  الخلل المُكتشف (أثبته `demo:verify:admin` على قاعدة التطوير):
--
--    `branches_select` تشترط صلاحية `organizations.branches.view`، ودور
--    «الاستقبال» لا يملك أي صلاحية `organizations.*`. النتيجة أن الاستقبال —
--    وهو **الدور الأساسي للحجز** — يرى صفر فرع، فتظهر قائمة الفروع في نموذج
--    الحجز فارغة ويستحيل عليه إنشاء أي حجز.
--
--    الخلل كامن منذ المرحلة 2 ولم يظهر لأن كل اختبارات الحجز السابقة أنشأت
--    الحجوزات بحساب مدير المنشأة، واختبار الاستقبال الوحيد كان **سلبيًا**
--    (رفض الحجز في فرع آخر) فمرّ بنجاح لسبب خاطئ.
--
--  الإصلاح — نفس النمط المعتمد سابقًا في النظام:
--    • `profiles_select_self`      : يقرأ المستخدم ملفه بلا صلاحية عرض المستخدمين.
--    • `role_permissions_select_own`: يقرأ صلاحياته بلا صلاحية عرض الأدوار.
--    • `branches_select_own` (هنا) : يقرأ فروعه بلا صلاحية عرض الفروع.
--
--    المنطق واحد: صلاحية «العرض» تخصّ **تصفّح** كل فروع المنشأة وإدارتها،
--    لا معرفة الفرع الذي يعمل فيه المستخدم — وبدون ذلك لا يعمل النظام أصلًا.
--
--  ⚠️ لا توسيع للنطاق: الفروع المرئية هنا هي **بالضبط** ما في `user_branches`
--     لهذا المستخدم، ولا شيء غيرها. صاحب نطاق المنشأة يبقى محكومًا بالسياسة
--     الأصلية التي تشترط الصلاحية.
--  ⚠️ لا تغيير في صلاحيات أي دور: قائمة صلاحيات الأدوار قرار عمل غير معتمد
--     (P-16)، وتعديلها هنا كان سيكون اختراعًا لقاعدة عمل.
-- =============================================================================

drop policy if exists branches_select_own on public.branches;
create policy branches_select_own on public.branches
  for select to authenticated
  using (
    (select app.is_active_user())
    and organization_id = (select app.current_org_id())
    and deleted_at is null
    and exists (
      select 1 from public.user_branches ub
      where ub.user_id = (select auth.uid())
        and ub.branch_id = branches.id
    )
  );

comment on policy branches_select_own on public.branches is
  'يرى المستخدم الفروع المُسندة إليه دائمًا — لازم لتشغيل الحجز والعمليات. '
  'لا يمنح رؤية أي فرع آخر ولا أي صلاحية تعديل.';
